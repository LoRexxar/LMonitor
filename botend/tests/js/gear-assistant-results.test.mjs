import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root = new URL('../../../', import.meta.url);
const elements = new Map();
const context = {document: {querySelector: () => ({dataset: {}}), getElementById: id => {
  if (!elements.has(id)) elements.set(id, {});
  return elements.get(id);
}}};
vm.runInNewContext(fs.readFileSync(new URL('static/shared/js/wow-gear-sources.js', root), 'utf8'), context);
const helper = new URL('static/portal/js/gear_assistant_results.js', root);
if (fs.existsSync(helper)) vm.runInNewContext(fs.readFileSync(helper, 'utf8'), context);
const source = fs.readFileSync(new URL('static/portal/js/gear_assistant.js', root), 'utf8');
vm.runInNewContext(source.replace('  initialize();', 'globalThis.render = (plans, slots) => { builderBootstrap = {slots}; renderPlans(plans); };'), context);
// Synthetic contract fixture, not a real optimizer acceptance result.
const slots = ['head','neck','shoulders','back','chest','wrists','hands','waist','legs','feet','finger1','finger2','trinket1','trinket2','main_hand','off_hand'].map(key => ({key, label: `部位-${key}`}));
const gem = (id, quality, haste = 7) => ({item: {item_id: 9, name: '同名<宝石>'}, variant: {id, key: `gem-${id}`, crafting_quality: quality, stats: {haste}}});
const equipment = Object.fromEntries(slots.map(({key, label}) => [key, {slot_label: label, acquisition_source_label: '选定地下城 · 首领 & 宝库', selection_origin: 'catalog', item: {item_id: 1, name: `装备-${key}`, quality: 4}, variant: {id: 10, item_level: 334, track_label: '神话', track_rank: 6, track_max_rank: 6, stats: {haste: 999}, sources: [{type: 'raid', instance_zh: '不可误用的首个来源'}]}, resolvedStats: {haste: 60}, gems: []}]));
equipment.head.gems = [gem(21,2), gem(21,2), gem(22,3), gem(23,2,8)];
equipment.head.selection_origin = 'locked';
equipment.neck.selection_origin = 'owned';
equipment.back.embellishment = {item: {item_id: 33, name: '实际美化'}, variant: {id: 33, effects: [{description_zh: '美化效果<安全>'}]}};
equipment.wrists.variant.is_intrinsic_embellishment = true;
equipment.head.enchant = {item: {item_id: 40, name: '实际附魔'}, variant: {id: 40, crafting_quality: 3, stats: {crit: 15}}};
const plan = {key: 'p', name: '<方案>', distance: 1, percentages: {haste: 20}, equipped_count: 16, owned_count: 1, effect_count: 3, embellishment_count: 2, delve_myth_count: 1, equipment, flask: {key: 'haste', name: '实际合剂', stats: {haste: 123}}, missing_items: []};
equipment.neck.acquisition_sources = [{type: 'raid', instance_zh: '真实团本', instance_id: 1, encounter_id: 2, encounter_order: 3}];
equipment.back.acquisition_sources = [{type: 'crafted'}];
equipment.waist.acquisition_sources = [{type: 'mythic_plus', instance_zh: '大秘境', instance_id: -1, encounter_zh: '实际地下城'}];
const before = JSON.stringify(plan);
context.render([plan], slots);
const html = elements.get('assistant-results').innerHTML;
assert.equal((html.match(/data-plan-slot=/g) || []).length, slots.length, '完整装备列表必须覆盖全部 canonical 槽位');
assert.equal((html.match(/data-gem-group=/g) || []).length, 3, '同名不同品质、不同变体不可合并');
for (const value of ['实际合剂', '急速 +123', '品质 2', '品质 3', '×2', '实际附魔', '实际美化', '固有美化', '神话 6/6', '已锁定', '来自备选', '需获取', '急速 +60', '选定地下城 · 首领 &amp; 宝库', '&lt;方案&gt;', '同名&lt;宝石&gt;', '美化效果&lt;安全&gt;']) assert.ok(html.includes(value), value);
assert.ok(!/物品 ID|变体 ID|gem-21|gem-22|gem-23/.test(html), 'tooltip 不显示内部身份，但保留分组精度');
assert.ok(!/未选择附魔|未镶嵌宝石|未选择宝石/.test(html), '没有宝石或附魔时不显示空态行');
assert.ok(!html.includes('不可误用的首个来源'));
assert.ok(!html.includes('急速 +999'));
assert.ok(!html.includes('宝石与附魔已计入最终属性'));
assert.ok(!html.includes('同名<宝石>'));
assert.match(html, /data-apply-plan="p"/);
assert.match(html, /<section class="assistant-plan-equipment"/);
assert.ok(!html.includes('<details'), '完整列表默认可见，不再嵌套折叠详情');
assert.equal((html.match(/class="assistant-item-trigger"/g) || []).length, slots.length);
const visible = html.replace(/<[^>]+>/g, '');
assert.ok(!visible.includes('急速 +60'), '装备属性仅在 tooltip 中');
assert.ok(!visible.includes('物品 ID'), '身份明细仅在 tooltip 中');
assert.ok(visible.includes('选定地下城'), '来源须在装备清单直接可见');
assert.equal((html.match(/class="assistant-result-source"/g) || []).length, slots.length);
assert.ok(visible.includes('装备-head'));
for (const source of ['真实团本3号', '专业制造', '实际地下城']) assert.ok(visible.includes(source), source);
assert.equal(context.WowGearSources.shortSourceText({sources: equipment.neck.acquisition_sources}, {raid_boss_numbers: {1: {2: 5}}}), '真实团本5号');
assert.equal(context.WowGearSources.shortSourceText({sources: []}), '来源待补全');
assert.ok(visible.includes('实际合剂'));
assert.equal(JSON.stringify(plan), before, '展示不得修改优化结果');
context.render([{...plan, equipment: {}, flask: {key: 'none', name: '任意旧名', stats: {}}}], slots);
const empty = elements.get('assistant-results').innerHTML;
assert.ok(empty.includes('不使用属性合剂'));
assert.ok(empty.includes('本方案未镶嵌宝石'));
assert.ok(!empty.includes('实际附魔'));
assert.ok(!empty.includes('全部装备均已拥有'));
console.log('PASS: 完整槽位、准确变体/来源/强化、合剂、转义、空态及应用入口；纯展示不修改结果');
